# A function that adds two numbers together and returns their sum.
def add(a: int, b: int) -> int:
    """A function that adds two numbers together and returns their sum.

    :param a: (int) First number.
    :param b: (int) Second number.
    :return: (int) Sum.
    """
    return a + b


